UPDATE step_algorithm sa
JOIN model_step ms ON ms.id = sa.step_id
SET sa.ql_expression = CASE sa.algorithm_code
    WHEN 'PLAN_CONSTRUCTION_WEIGHT_CALC' THEN 'PLAN_CONSTRUCTION_NORM * weight_L2_PLAN_CONSTRUCTION'
    WHEN 'HAZARD_INSPECTION_WEIGHT_CALC' THEN 'HAZARD_INSPECTION_NORM * weight_L2_HAZARD_INSPECTION'
    WHEN 'RISK_ASSESSMENT_WEIGHT_CALC' THEN 'RISK_ASSESSMENT_NORM * weight_L2_RISK_ASSESSMENT'
    WHEN 'FINANCIAL_INPUT_WEIGHT_CALC' THEN 'FINANCIAL_INPUT_NORM * weight_L2_FUNDING'
    WHEN 'MATERIAL_RESERVE_WEIGHT_CALC' THEN 'MATERIAL_RESERVE_NORM * weight_L2_MATERIAL'
    WHEN 'MEDICAL_SUPPORT_WEIGHT_CALC' THEN 'MEDICAL_SUPPORT_NORM * weight_L2_MEDICAL'
    WHEN 'SELF_MUTUAL_AID_WEIGHT_CALC' THEN 'SELF_MUTUAL_AID_NORM * weight_L2_SELF_RESCUE'
    WHEN 'PUBLIC_EVACUATION_WEIGHT_CALC' THEN 'PUBLIC_EVACUATION_NORM * weight_L2_PUBLIC_AVOIDANCE'
    WHEN 'RELOCATION_SHELTER_WEIGHT_CALC' THEN 'RELOCATION_SHELTER_NORM * weight_L2_RELOCATION'
    WHEN 'PLAN_CONSTRUCTION_COMPREHENSIVE' THEN 'PLAN_CONSTRUCTION_NORM * weight_L1_DISASTER_MANAGEMENT * weight_L2_PLAN_CONSTRUCTION'
    WHEN 'HAZARD_INSPECTION_COMPREHENSIVE' THEN 'HAZARD_INSPECTION_NORM * weight_L1_DISASTER_MANAGEMENT * weight_L2_HAZARD_INSPECTION'
    WHEN 'RISK_ASSESSMENT_COMPREHENSIVE' THEN 'RISK_ASSESSMENT_NORM * weight_L1_DISASTER_MANAGEMENT * weight_L2_RISK_ASSESSMENT'
    WHEN 'FINANCIAL_INPUT_COMPREHENSIVE' THEN 'FINANCIAL_INPUT_NORM * weight_L1_DISASTER_MANAGEMENT * weight_L2_FUNDING'
    WHEN 'MATERIAL_RESERVE_COMPREHENSIVE' THEN 'MATERIAL_RESERVE_NORM * weight_L1_DISASTER_PREPAREDNESS * weight_L2_MATERIAL'
    WHEN 'MEDICAL_SUPPORT_COMPREHENSIVE' THEN 'MEDICAL_SUPPORT_NORM * weight_L1_DISASTER_PREPAREDNESS * weight_L2_MEDICAL'
    WHEN 'SELF_MUTUAL_AID_COMPREHENSIVE' THEN 'SELF_MUTUAL_AID_NORM * weight_L1_SELF_RESCUE_TRANSFER * weight_L2_SELF_RESCUE'
    WHEN 'PUBLIC_EVACUATION_COMPREHENSIVE' THEN 'PUBLIC_EVACUATION_NORM * weight_L1_SELF_RESCUE_TRANSFER * weight_L2_PUBLIC_AVOIDANCE'
    WHEN 'RELOCATION_SHELTER_COMPREHENSIVE' THEN 'RELOCATION_SHELTER_NORM * weight_L1_SELF_RESCUE_TRANSFER * weight_L2_RELOCATION'
    ELSE sa.ql_expression
END
WHERE ms.model_id = 8
  AND sa.algorithm_code IN (
    'PLAN_CONSTRUCTION_WEIGHT_CALC',
    'HAZARD_INSPECTION_WEIGHT_CALC',
    'RISK_ASSESSMENT_WEIGHT_CALC',
    'FINANCIAL_INPUT_WEIGHT_CALC',
    'MATERIAL_RESERVE_WEIGHT_CALC',
    'MEDICAL_SUPPORT_WEIGHT_CALC',
    'SELF_MUTUAL_AID_WEIGHT_CALC',
    'PUBLIC_EVACUATION_WEIGHT_CALC',
    'RELOCATION_SHELTER_WEIGHT_CALC',
    'PLAN_CONSTRUCTION_COMPREHENSIVE',
    'HAZARD_INSPECTION_COMPREHENSIVE',
    'RISK_ASSESSMENT_COMPREHENSIVE',
    'FINANCIAL_INPUT_COMPREHENSIVE',
    'MATERIAL_RESERVE_COMPREHENSIVE',
    'MEDICAL_SUPPORT_COMPREHENSIVE',
    'SELF_MUTUAL_AID_COMPREHENSIVE',
    'PUBLIC_EVACUATION_COMPREHENSIVE',
    'RELOCATION_SHELTER_COMPREHENSIVE'
  );
