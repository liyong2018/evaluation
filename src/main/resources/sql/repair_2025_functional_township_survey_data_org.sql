CREATE TABLE IF NOT EXISTS survey_data_bak_2025_functional_township_repair_20260505 AS
SELECT s.*
FROM survey_data s
JOIN tmp_functional_township_mapping m
  ON LEFT(s.region_code, 9) COLLATE utf8mb4_unicode_ci IN (m.source_code, m.target_code)
WHERE s.year = 2025;

UPDATE survey_data s
JOIN tmp_functional_township_mapping m
  ON LEFT(s.region_code, 9) COLLATE utf8mb4_unicode_ci IN (m.source_code, m.target_code)
SET
  s.region_code = CASE
    WHEN LEFT(s.region_code, 9) COLLATE utf8mb4_unicode_ci = m.source_code THEN CONCAT(m.target_code, SUBSTRING(s.region_code, 10))
    ELSE s.region_code
  END,
  s.province = '四川省',
  s.city = m.city_name,
  s.county = m.county_name,
  s.township = m.township_name,
  s.update_time = NOW()
WHERE s.year = 2025;

SELECT 'survey_old_source_prefix_remaining' AS item, COUNT(*) AS cnt
FROM survey_data
WHERE year = 2025
  AND LEFT(region_code, 9) IN (
    '510116003', '510116018', '510116020', '510116019', '510116022',
    '510116021', '510116025', '510116023', '510116024', '510107062',
    '510107061', '510107063', '510107064', '510116004', '510117020',
    '510117019', '510185013', '510185009', '510185010', '510185017',
    '510185015', '510185016', '510185014', '510185012', '510185126',
    '510185127', '510185128', '510185132', '510185131', '510185121',
    '510173715', '510302008', '510302006', '510302009', '510302005',
    '510311001'
  );

SELECT LEFT(region_code, 6) AS county_code, county AS county_name, COUNT(*) AS cnt
FROM survey_data
WHERE year = 2025 AND LEFT(region_code, 6) IN ('510171', '510172', '510173', '510371')
GROUP BY LEFT(region_code, 6), county
ORDER BY county_code, county_name;
